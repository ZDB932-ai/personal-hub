import { createRequire } from 'node:module'
import { mkdirSync } from 'node:fs'
import assert from 'node:assert/strict'
const require=createRequire(import.meta.url)
const {chromium}=require(process.env.PHUB_PLAYWRIGHT_MODULE ?? 'playwright')
const url=process.env.PHUB_VERIFY_URL ?? 'http://127.0.0.1:4183'
const browser=await chromium.launch({channel:process.env.PHUB_BROWSER_CHANNEL ?? 'msedge',headless:true})
const page=await browser.newPage({viewport:{width:1280,height:900}})
page.setDefaultTimeout(20000)
const errors=[]; page.on('pageerror',e=>errors.push(e.message))
try {
await page.goto(url)
await page.getByRole('button',{name:'仅在本机使用 / 旧版设备加入',exact:true}).click()
await page.getByPlaceholder('创建主密码',{exact:true}).fill('QA-Layout-Password')
await page.getByPlaceholder('再次输入主密码',{exact:true}).fill('QA-Layout-Password')
await page.getByPlaceholder('例如：我的工作台').fill('自动验收账户')
  await page.getByRole('button', { name: '下一步：保存恢复密钥', exact: true }).click()
  const recoveryCode = await page.locator('textarea[readonly]').inputValue()
  await page.getByLabel('确认密钥最后 8 位').fill(recoveryCode.slice(-8))
  await page.getByRole('checkbox', { name: '我已在应用之外保存完整密钥' }).check()
  await page.getByRole('button', { name: '确认保存并启用', exact: true }).click()
await page.getByRole('button',{name:'锁定',exact:true}).first().waitFor()
await page.goto(`${url}/#/today`)
await page.getByLabel('快速添加任务',{exact:true}).fill('整理今天的资料')
await page.getByRole('button',{name:'确认添加',exact:true}).click()
await page.getByLabel('快速添加任务',{exact:true}).fill('准备明日会议')
await page.getByRole('button',{name:'确认添加',exact:true}).click()
await page.getByRole('button',{name:'设为重点：准备明日会议',exact:true}).click()
await page.getByRole('button',{name:'取消重点：准备明日会议',exact:true}).waitFor()
assert.equal(await page.getByPlaceholder('搜索任务',{exact:true}).isVisible(),false)
await page.getByRole('button',{name:'搜索与筛选任务',exact:true}).click()
await page.getByPlaceholder('搜索任务',{exact:true}).fill('整理')
assert.equal(await page.getByRole('button',{name:'取消重点：准备明日会议',exact:true}).count(),0)
await page.getByRole('button',{name:'清除筛选',exact:true}).click()
await page.getByRole('button',{name:'搜索与筛选任务',exact:true}).click()
await page.getByRole('button',{name:'安排设置',exact:true}).click()
await page.locator('summary').filter({hasText:'今天的节奏'}).click()
await page.getByRole('group',{name:'选择今天的节奏',exact:true}).waitFor()
await page.getByRole('button',{name:'安排设置',exact:true}).click()
mkdirSync('.visual-qa/today-simple',{recursive:true})
await page.screenshot({path:'.visual-qa/today-simple/desktop.png',fullPage:true})
await page.setViewportSize({width:390,height:844})
await page.screenshot({path:'.visual-qa/today-simple/mobile.png',fullPage:true})
assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth > innerWidth),false)
assert.deepEqual(errors,[])
console.log('PASS: 添加、重点、搜索、安排设置、移动端无横向溢出')
} finally {await browser.close()}
