import { createRequire } from 'node:module'
import { mkdirSync, writeFileSync } from 'node:fs'
import { resolve, join } from 'node:path'
import assert from 'node:assert/strict'

const require = createRequire(import.meta.url)
const { chromium } = require(process.env.PHUB_PLAYWRIGHT_MODULE ?? 'playwright')
const dir = resolve('.visual-qa', `hub-${Date.now()}`)
mkdirSync(dir, { recursive: true })
const browser = await chromium.launch({ channel: process.env.PHUB_BROWSER_CHANNEL ?? 'msedge', headless: true })
const context = await browser.newContext({ viewport: { width: 1280, height: 900 } })
const page = await context.newPage()
const errors = [], results = []
const pass = message => { results.push(message); console.log(`PASS: ${message}`) }
const button = name => page.getByRole('button', { name, exact: true })
const search = async () => { await page.waitForFunction(() => !document.querySelector('[role="dialog"]')); await page.keyboard.press('Control+k'); await page.getByRole('heading', { name: '全局搜索与收集' }).waitFor() }
const settings = async () => { await button('设置').first().click(); await button('备份').click() }
page.setDefaultTimeout(20000)
page.on('pageerror', error => errors.push(error.message))
page.on('dialog', dialog => dialog.accept())
try {
  await page.goto(process.env.PHUB_VERIFY_URL ?? 'http://127.0.0.1:4183')
  await page.getByPlaceholder('创建主密码', { exact: true }).fill('QA-Hub-Password')
  await page.getByPlaceholder('再次输入主密码', { exact: true }).fill('QA-Hub-Password')
  await page.getByPlaceholder('例如：我的工作台').fill('自动验收账户')
  await page.getByRole('button', { name: '下一步：保存恢复密钥', exact: true }).click()
  const recoveryCode = await page.locator('textarea[readonly]').inputValue()
  await page.getByLabel('确认密钥最后 8 位').fill(recoveryCode.slice(-8))
  await page.getByRole('checkbox', { name: '我已在应用之外保存完整密钥' }).check()
  await page.getByRole('button', { name: '确认保存并启用', exact: true }).click()
  await button('锁定').first().waitFor()
  await search()
  await button('新建备忘录').click()
  await page.getByPlaceholder('一句话主题（选填）').fill('项目资料源')
  await page.getByPlaceholder('随手记点什么…').fill('需要整理实验记录 #研究')
  await button('创建便签').click()
  await search()
  await page.getByRole('dialog').getByRole('button', { name: '新建任务', exact: true }).click()
  await page.getByPlaceholder('要做什么？').fill('整理研究资料')
  await page.getByPlaceholder('未填写时，排期按 30 分钟估算').fill('90')
  await page.getByPlaceholder('如：工作, 重要').fill('研究, 阅读')
  await page.getByPlaceholder('输入名称查找关联条目').fill('项目资料源')
  await button('添加 · 备忘录 · 项目资料源').click()
  await button('添加任务').click()
  await search()
  await page.getByLabel('搜索所有内容').fill('整理研究')
  await page.getByRole('button', { name: /任务.*整理研究资料/ }).click()
  assert.equal(await page.getByPlaceholder('未填写时，排期按 30 分钟估算').inputValue(), '90')
  assert.match(await page.getByPlaceholder('如：工作, 重要').inputValue(), /研究/)
  await button('备忘录 · 项目资料源').waitFor()
  await page.getByPlaceholder('要做什么？').fill('整理研究资料新版')
  await button('保存修改').click()
  pass('全局收集、搜索、任务预计时长、标签与备忘录引用可保存编辑')
  await button('锁定').first().click()
  await page.getByPlaceholder('主密码', { exact: true }).fill('QA-Hub-Password')
  await button('登录').click()
  await button('锁定').first().waitFor()
  await settings()
  await button('修改历史').click()
  await page.getByText('整理研究资料', { exact: true }).waitFor()
  await button('恢复为副本').first().click()
  await page.getByText('已恢复副本，可回到对应页面查看', { exact: true }).waitFor()
  await page.keyboard.press('Escape')
  await search()
  await page.getByLabel('搜索所有内容').fill('整理研究资料')
  assert.equal(await page.getByRole('button', { name: /任务.*整理研究资料/ }).count(), 2)
  pass('重新解锁后历史保留，恢复生成副本且当前任务保留')
  await page.keyboard.press('Escape')
  await page.goto((process.env.PHUB_VERIFY_URL ?? 'http://127.0.0.1:4183') + '/#/today')
  await button('安排设置').click()
  await page.getByText('时间留白', { exact: false }).waitFor()
  await page.getByPlaceholder('留空：跟随每日精力').fill('60')
  await button('保存时间').click()
  await page.getByText(/可用 60 分钟/).waitFor()
  pass('每日容量可编辑并展示')
  await search()
  await page.locator('input[type=file]').last().setInputFiles({ name: 'qa-research.txt', mimeType: 'text/plain', buffer: Buffer.from('正文唯一词汇Nebula实验记录') })
  await page.getByText('已加密保存到资料库', { exact: true }).waitFor()
  await page.keyboard.press('Escape')
  await page.goto((process.env.PHUB_VERIFY_URL ?? 'http://127.0.0.1:4183') + '/#/docs')
  await page.locator('summary').filter({ hasText: '更多操作' }).first().click()
  await button('提取正文用于搜索').click()
  await button('重新提取正文').waitFor()
  await search()
  await page.getByLabel('搜索所有内容').fill('Nebula')
  await page.getByRole('button', { name: /资料.*qa-research.txt/ }).waitFor()
  await page.keyboard.press('Escape')
  await button('锁定').first().click()
  await page.getByPlaceholder('主密码', { exact: true }).fill('QA-Hub-Password')
  await button('登录').click()
  await button('锁定').first().waitFor()
  await search()
  await page.getByLabel('搜索所有内容').fill('Nebula')
  await page.getByText('没有找到匹配内容，可以换个关键词。').waitFor()
  pass('正文提取参与搜索，锁定清空正文索引')
  await page.keyboard.press('Escape')
  for (const width of [375, 768, 1024, 1440]) {
    await page.setViewportSize({ width, height: 900 })
    await search()
    await page.getByLabel('搜索所有内容').fill('研究')
    await page.getByRole('heading', { name: '全局搜索与收集' }).waitFor({ state: 'visible' })
    await page.waitForFunction(() => {
      const overlay = document.querySelector('[role="dialog"]')?.parentElement
      return overlay && !overlay.className.includes('modal-enter') && getComputedStyle(overlay).opacity === '1'
    })
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
    await page.screenshot({ path: join(dir, `search-${width}.png`) })
    await page.keyboard.press('Escape')
  }
  pass('375/768/1024/1440 搜索布局无页面横向滚动')
  assert.deepEqual(errors, [])
} catch (error) {
  await page.screenshot({ path: join(dir, 'failure.png') }).catch(() => {})
  throw error
} finally {
  writeFileSync(join(dir, 'report.json'), JSON.stringify({ results, errors }, null, 2))
  console.log(`REPORT: ${dir}`)
  await browser.close()
}
