import { createRequire } from 'node:module'
import { mkdirSync } from 'node:fs'
import assert from 'node:assert/strict'
const require = createRequire(import.meta.url)
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')
const browser = await chromium.launch({ channel: 'msedge', headless: true })
const context = await browser.newContext({ viewport: { width: 1280, height: 900 } })
const page = await context.newPage()
const base = process.env.QA_URL || 'http://127.0.0.1:4187'
const errors = []
page.on('pageerror', error => errors.push(error.message))
mkdirSync('.visual-qa/appearance-studio', { recursive: true })
const cfg = () => page.evaluate(() => JSON.parse(localStorage.getItem('xk.wallpaper.v1')))
async function capture(name) { await page.screenshot({ path: `.visual-qa/appearance-studio/${name}.png`, animations: 'disabled' }) }
try {
  await page.goto(base)
  await page.getByPlaceholder('创建主密码', { exact: true }).fill('QA-Art-Studio-Only')
  await page.getByPlaceholder('再次输入主密码', { exact: true }).fill('QA-Art-Studio-Only')
  await page.getByRole('button', { name: '创建并进入', exact: true }).click()
  await page.getByRole('button', { name: '设置', exact: true }).click()
  for (const name of ['日光工作室', '深海指挥台', '暮色手帐', '云端花园']) {
    await page.getByRole('button', { name: `应用${name}`, exact: true }).click()
    await page.waitForFunction(() => !!document.querySelector('.wallpaper-layer'))
  }
  await capture('scenes')
  await page.getByRole('button', { name: '撤销搭配', exact: true }).click()
  assert.equal((await cfg()).builtin, 'dunes')
  await page.getByRole('button', { name: '背景设置', exact: true }).click()
  await page.getByRole('button', { name: '风景', exact: true }).click()
  assert.equal(await page.getByRole('button', { name: /^使用壁纸：/ }).count(), 4)
  await page.getByRole('button', { name: '全部', exact: true }).click()
  assert.equal(await page.getByRole('button', { name: /^使用壁纸：/ }).count(), 14)
  for (const image of await page.locator('.wallpaper-gallery img').all()) {
    await image.scrollIntoViewIfNeeded()
    await image.evaluate(el => el.decode())
  }
  await page.getByRole('checkbox', { name: /自动平衡明暗/ }).uncheck()
  await page.getByRole('slider', { name: '遮罩强度', exact: true }).fill('70')
  assert.equal((await cfg()).dim, 70)
  await page.getByText('构图与质感', { exact: true }).click()
  await page.getByRole('slider', { name: '背景柔化', exact: true }).fill('8')
  await page.getByRole('slider', { name: '水平构图', exact: true }).fill('75')
  await page.getByRole('slider', { name: '画面缩放', exact: true }).fill('120')
  assert.equal((await cfg()).blur, 8)
  await page.getByRole('button', { name: '重置调节', exact: true }).click()
  assert.equal((await cfg()).blur, 0)
  await page.getByRole('checkbox', { name: /透明信息框/ }).check()
  await page.getByRole('slider', { name: '信息框透明度', exact: true }).fill('60')
  assert.equal((await cfg()).panelTransparency, 60)
  assert.equal(await page.locator('.wallpaper-reading').count(), 0)
  const panel = await page.locator('.workspace-panel').first().evaluate(el => ({ bg: getComputedStyle(el).backgroundColor, opacity: getComputedStyle(el).opacity }))
  assert.equal(panel.opacity, '1')
  assert.ok(panel.bg.includes('0.4'))
  await page.keyboard.press('Escape')
  await page.getByRole('dialog').waitFor({ state: 'hidden' })
  await page.goto(`${base}/#/today`)
  await page.locator('.page-header').waitFor()
  await page.evaluate(() => window.scrollTo(0, 0))
  const layout = await page.evaluate(() => {
    const sidebar = document.querySelector('.desktop-sidebar').getBoundingClientRect()
    const content = document.querySelector('.desktop-main > div').getBoundingClientRect()
    return { top: Math.abs(sidebar.top - content.top), height: content.height, minimumHeight: innerHeight - 24, gap: content.left - sidebar.right, right: innerWidth - content.right }
  })
  assert.ok(layout.top <= 1 && layout.height >= layout.minimumHeight, JSON.stringify(layout))
  assert.equal(layout.gap, 12)
  assert.equal(layout.right, 12)
  await capture('transparent-panels')
  await page.goto(`${base}/#/`)
  await page.locator('.workspace-panel').first().waitFor()
  await page.getByRole('button', { name: '设置', exact: true }).click()
  await page.getByRole('button', { name: '背景设置', exact: true }).click()
  await page.getByLabel('上传壁纸文件', { exact: true }).setInputFiles('public/wallpapers/solar.jpg')
  await page.getByRole('button', { name: '使用自定义图片', exact: true }).waitFor()
  assert.equal((await cfg()).custom, true)
  await page.getByRole('button', { name: '使用壁纸：深海流光', exact: true }).click()
  await page.getByRole('button', { name: '使用自定义图片', exact: true }).click()
  await page.getByLabel('上传壁纸文件', { exact: true }).setInputFiles({ name: 'broken.jpg', mimeType: 'image/jpeg', buffer: Buffer.from('invalid-image') })
  await page.getByText('无法解码这张图片，请换一张有效的静态图片', { exact: true }).waitFor()
  assert.equal((await cfg()).custom, true)
  await page.reload()
  await page.getByPlaceholder('主密码', { exact: true }).fill('QA-Art-Studio-Only')
  assert.equal(await page.locator('.wallpaper-layer').count(), 0)
  await page.getByRole('button', { name: '解锁', exact: true }).click()
  await page.getByRole('button', { name: '设置', exact: true }).click()
  await page.getByRole('button', { name: '背景设置', exact: true }).click()
  await page.getByRole('button', { name: '使用自定义图片', exact: true }).waitFor()
  await page.getByRole('button', { name: '使用壁纸：云端花园', exact: true }).click()
  assert.equal((await cfg()).transparentPanels, true)
  assert.equal((await cfg()).panelTransparency, 60)
  await page.getByRole('heading', { name: '壁纸与透明度', exact: true }).scrollIntoViewIfNeeded()
  await capture('wallpaper-desktop')
  await page.getByRole('button', { name: '手机构图', exact: true }).click()
  await page.getByRole('button', { name: '放大壁纸预览', exact: true }).click()
  assert.equal(await page.getByRole('dialog').count(), 2)
  await page.keyboard.press('Escape')
  await page.waitForFunction(() => document.querySelectorAll('[role=dialog]').length === 1)
  await page.setViewportSize({ width: 375, height: 812 })
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false)
  await page.getByRole('heading', { name: '壁纸与透明度', exact: true }).scrollIntoViewIfNeeded()
  await capture('wallpaper-mobile')
  page.once('dialog', dialog => dialog.dismiss())
  await page.getByRole('button', { name: '删除我的图片', exact: true }).click()
  assert.equal(await page.getByRole('button', { name: '使用自定义图片', exact: true }).count(), 1)
  page.once('dialog', dialog => dialog.accept())
  await page.getByRole('button', { name: '删除我的图片', exact: true }).click()
  await page.getByRole('button', { name: '使用自定义图片', exact: true }).waitFor({ state: 'hidden' })
  assert.deepEqual(errors, [])
  console.log('PASS: 四场景、撤销、十四张资源、分类、解码、调节/重置、上传/错误保护、刷新、自定义重选、锁屏隐私、双层预览、手机无溢出、删除取消与确认')
} finally { await browser.close() }
