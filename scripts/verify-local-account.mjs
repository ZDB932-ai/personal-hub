  await page.getByPlaceholder('输入完整的 8 组恢复密钥').fill(code)
  await b('重设密码').click()
  await page.getByText('密码已重设，数据已保留。请使用新密码登录。', { exact:true }).waitFor()
  await page.getByPlaceholder('主密码', {exact:true}).fill('Account-QA-2026')
